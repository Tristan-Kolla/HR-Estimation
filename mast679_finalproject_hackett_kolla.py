"""## Kernel Density Estimator (Section 3.3.2)

Kernel Density Estimator (KDE) estimates the utilization distribution. This method shows core use areas of the bird while reducing the outlier effect. However, this method can be sensitive to bandwidth and can include unused areas. This method also assume independence of all data points.

Selection of bandwidth is important in KDE because it determines the smoothness of the resulting density estimate. Bandwidth can be found by 'rule of thumb' or cross validation. We use unbiased cross validation, leave-one-out cross validation, and Scott's rule of thumb.

Unbiased Cross-Validation (UCV) minimizes the integrated square error of the density estimate to select an optimal bandwidth.

Manual Leave-One-Out Cross-Validation (MLCV) evaluates the likelihood of each data point being generated by the KDE model, which is trained on the remaining data points

Scott's Rule of Thumb provides a straightforward calculation for bandwidth based on the data's variance and sample size.

We chose to use Scott's Rule of Thumb in our final analysis, as this is typically the standard for KDE, which gives a home range estimate of 5.88km^2
"""

