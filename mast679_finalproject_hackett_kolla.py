LON_COL   = "location-long"
ID_COL    = "individual-local-identifier"
UTM_EPSG  = 32618                     # adjust to your UTM zone

GRID_H    = np.linspace(100, 1200, 30) # bandwidth candidates
CELL      = 250                       # grid cell size for raster
LEVEL     = 0.95                      # 95% contour

BIRD_ID   = "A114"

# ── 3. Helper functions ─────────────────────────────────────────
def gaussian_kernel(u2):
    return (2 * np.pi)**-1 * np.exp(-0.5 * u2)

def convolved_kernel(u2):
    return (4 * np.pi)**-1 * np.exp(-0.25 * u2)

def pairwise_sqdist(xy):
    return pdist(xy, metric='sqeuclidean')

def unbiased_cv(xy):
    """Unbiased Least-Squares Cross-Validation (UCV)."""
    n, d2 = len(xy), pairwise_sqdist(xy)
    best_h, best_score = None, np.inf
    for h in GRID_H:
        h2 = h * h
        t1 = (1/(n*(n-1)*h2)) * np.sum(convolved_kernel(d2/h2))
        t2 = (2/(n*h2)) * np.sum(gaussian_kernel(d2/h2))
        score = t1 - t2
        if score < best_score:
            best_h, best_score = h, score
    return best_h

def mlcv_manual(xy):
    """Manual Leave-One-Out Likelihood CV."""
    n = len(xy)
    best_h, best_score = None, -np.inf
    for h in GRID_H:
        scores = []
        for i in range(n):
            leave_one_out = np.delete(xy, i, axis=0)
            kde = gaussian_kde(leave_one_out.T, bw_method=h/np.std(leave_one_out, 0).mean())
            score = np.log(kde(xy[i]))
            scores.append(score)
        avg_score = np.mean(scores)
        if avg_score > best_score:
            best_h, best_score = h, avg_score
    return best_h

def scott_rule(xy):
    """Scott's rule of thumb."""
    n, d = len(xy), xy.shape[1]
    factor = n ** (-1. / (d + 4))
    avg_std = np.std(xy, axis=0).mean()
    return factor * avg_std

def kde95_polygon(xy, h):
    kde = gaussian_kde(xy.T, bw_method=h/np.std(xy, 0).mean())

    xmin, ymin = xy.min(0) - 3*h
    xmax, ymax = xy.max(0) + 3*h
    nx = int((xmax - xmin)/CELL) + 1
    ny = int((ymax - ymin)/CELL) + 1

    xx, yy = np.mgrid[xmin:xmax:nx*1j, ymin:ymax:ny*1j]
    zz = kde(np.vstack([xx.ravel(), yy.ravel()])).reshape(xx.shape)

    threshold = np.percentile(zz, (1-LEVEL)*100)
    mask = (zz >= threshold).astype("uint8")

    shapes_iter = features.shapes(mask, transform=from_origin(xmin, ymax, CELL, CELL))
    polys = [shape(geom) for geom, val in shapes_iter if val == 1]
    return unary_union(polys) if polys else None

