"""## k-Local Convex Hull Method (Section 3.3.3)

k-Local Convex Hull (k-LoCoH) constructs a range by combining convex hulls of local point clusters, using k nearest neighbours.

This method captures landscape structure and reveal travel corridors. However, this method is more complex and requires tuning of k. Finding an optimal k can be done using cross-validation, however much of the literature using 'rule of thumb', so we will follow with that by using a fixed k that can be tweaked by the user. We chose k=10 for a good trade-off between overestimation and underestimation, which gives a home range estimate of 0.32km^2
"""

