def kde95_polygon(xy, bandwidth=100, cell=250, level=0.95):
    if len(xy) < 5:
        return None
    kde = gaussian_kde(xy.T)
    xmin, ymin = xy.min(0) - 3*bandwidth
    xmax, ymax = xy.max(0) + 3*bandwidth
    nx = int((xmax - xmin) / cell) + 1
    ny = int((ymax - ymin) / cell) + 1
    xx, yy = np.mgrid[xmin:xmax:nx*1j, ymin:ymax:ny*1j]
    zz = kde(np.vstack([xx.ravel(), yy.ravel()])).reshape(xx.shape)

    thresh = np.percentile(zz, (1-level)*100)     # 5-th percentile for 95 %
    mask   = (zz >= thresh).astype("uint8")

    shapes = features.shapes(
        mask,
        transform=from_origin(xmin, ymax, cell, cell)
    )
    polys = [shape(geom) for geom, val in shapes if val == 1]
    return unary_union(polys) if polys else None

