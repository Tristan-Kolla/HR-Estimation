"""## Method Comparison (Section 3.3.4)

**Comparison**

MCP draws the smallest convex shape that covers all GPS points. This method is simple, which makes comparison of different birds easy. However, this method can overestimate the home range since it is very sensitive to outliers.

KDE puts points into a density surface and draws a contour (in our case, 95% contour). This method is useful for finding core areas and smooths random movements from the birds. However, this method can include areas that the bird has not visited. Also, the choice of bandwidth is critical to KDE.

k-LoCoH builds many small hulls based on the k nearest neighbours of points and merges them. This method is useful in capturing barriers (although this is not much of a worry with birds), it preserves fine structure, and is not affected much by outliers. However, this method is more complex, so it may be slower, and it requires a careful choice of k.

**Conclusion**

Overall, k-LoCoH gives a more realistic and ecologically significant home range for the birds. This method respects boundaries, such as urban areas, and it tightly hugs the points, with no smoothing beyond where the birds actually went. k-LoCoH can also show multiple core areas if the bird uses different patches, and avoids overestimation when a few exploratory points happen.
"""

