FILE = "gps_data.csv"
K_LOCOH = 10 # fixed k (can change to different values)
LEVEL = 0.95 # 95% contour (can change level)
CELL = 250  # Raster cell size for KDE

# read data and drop empty location rows
df = pd.read_csv(FILE).dropna(subset=['location-lat', 'location-long'])

# convert to GeoDataFrame
gdf = gpd.GeoDataFrame(
    df,
    geometry=gpd.points_from_xy(df['location-long'], df['location-lat']),
    crs="EPSG:4326"
)

# UTM zone based on mean longitude
longitude = gdf.geometry.x.mean()
utm_zone = int((longitude + 180)/6) + 1
UTM_EPSG = 32600 + utm_zone  # For Northern Hemisphere

# Project data to UTM
gdf_utm = gdf.to_crs(epsg=UTM_EPSG)

# using scott's rule to choose a bandwidth for KDE
def scott_bandwidth(xy):
    n, d = xy.shape
    factor = n ** (-1. / (d + 4))
    avg_std = np.std(xy, axis=0).mean()
    return factor * avg_std

# KDE: points (xy) & bandwidth (h)
def kde95_polygon(xy, h):
    kde = gaussian_kde(xy.T, bw_method=h/np.std(xy, 0).mean())
    # build a raster grid that is big enough for the data and add some padding
    xmin, ymin = xy.min(0) - 3*h
    xmax, ymax = xy.max(0) + 3*h
    nx = int((xmax - xmin)/CELL) + 1
    ny = int((ymax - ymin)/CELL) + 1
    # KDE over the grid
    xx, yy = np.mgrid[xmin:xmax:nx*1j, ymin:ymax:ny*1j]
    zz = kde(np.vstack([xx.ravel(), yy.ravel()])).reshape(xx.shape)
    # 95% threshold
    threshold = np.percentile(zz, (1-LEVEL)*100)
    mask = (zz >= threshold).astype("uint8")
    # takes the 95% contour and merges multiple shapes into one
    shapes_iter = features.shapes(mask, transform=from_origin(xmin, ymax, CELL, CELL))
    polys = [shape(geom) for geom, val in shapes_iter if val == 1]
    return unary_union(polys) if polys else None

# iterate through each bird
bird_ids = gdf_utm['individual-local-identifier'].unique()

# tracking points for each bird
for bird_id in bird_ids:
    bird = gdf_utm[gdf_utm['individual-local-identifier'] == bird_id]
    if bird.empty:
        continue
    # numpy array of X/Y coordinates
    xy = np.column_stack((bird.geometry.x, bird.geometry.y))

    # skip bird with too few points
    if len(xy) < 10:
        print(f"Skipping {bird_id}: too few points ({len(xy)})")
        continue

    # MCP
    try:
        hull = ConvexHull(xy)
        hull_points = xy[hull.vertices]
        mcp_poly = Polygon(hull_points)
        mcp_area = mcp_poly.area / 1e6  # km²
    except:
        print(f"Skipping {bird_id}: MCP calculation failed")
        continue

    # KDE (Scott)
    h_scott = scott_bandwidth(xy)
    kde_poly = kde95_polygon(xy, h_scott)
    kde_area = kde_poly.area / 1e6 if kde_poly else np.nan

    # k-LoCoH
    try:
        # find k nearest
        nbrs = NearestNeighbors(n_neighbors=K_LOCOH).fit(xy)
        neigh_ix = nbrs.kneighbors(return_distance=False)
        # build a small convex hull around each point and its neighbours
        hulls = [MultiPoint(xy[ix]).convex_hull for ix in neigh_ix]
        hulls = [hull for hull in hulls if not hull.is_empty]
        # merge all hulls
        locoh_poly = unary_union(hulls)
        locoh_area = locoh_poly.area / 1e6
    except:
        print(f"Skipping {bird_id}: LoCoH calculation failed")
        continue

    # plot
    fig, ax = plt.subplots(figsize=(12, 12))

    bird.to_crs(3857).plot(ax=ax, color='black', markersize=5, label='GPS Points')

    gpd.GeoSeries([mcp_poly], crs=gdf_utm.crs).to_crs(3857).boundary.plot(
        ax=ax, edgecolor='blue', linewidth=2, label=f'MCP (Area: {mcp_area:.2f} km²)'
    )

    if kde_poly:
        gpd.GeoSeries([kde_poly], crs=gdf_utm.crs).to_crs(3857).boundary.plot(
            ax=ax, edgecolor='red', linewidth=2, label=f'KDE-Scott (Area: {kde_area:.2f} km²)'
        )

    gpd.GeoSeries([locoh_poly], crs=gdf_utm.crs).to_crs(3857).boundary.plot(
        ax=ax, edgecolor='green', linewidth=2, label=f'k-LoCoH (Area: {locoh_area:.2f} km²)'
    )

    ctx.add_basemap(ax, source=ctx.providers.OpenStreetMap.Mapnik, attribution=False)

    ax.set_title(f"{bird_id} – Home Range Estimates")
    ax.set_axis_off()
    ax.legend()
    plt.tight_layout()

    plt.show()
