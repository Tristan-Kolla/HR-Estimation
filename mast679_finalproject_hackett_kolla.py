# Load dataset

df = pd.read_csv("gps_data.csv")

# Rename
LAT_COL = "location-lat"
LON_COL = "location-long"
ID_COL = "individual-local-identifier"

# Drop rows with missing coordinates
df = df.dropna(subset=[LAT_COL, LON_COL])

# Create GeoDataFrame in WGS84 (for geographic locations), then project to UTM 18N (North America)
gdf = gpd.GeoDataFrame(
    df,
    geometry=gpd.points_from_xy(df[LON_COL], df[LAT_COL]),
    crs="EPSG:4326"
).to_crs(epsg=32618)

# Loop through each bird ID
unique_ids = gdf[ID_COL].unique()

for bird_id in unique_ids:
    bird_points = gdf[gdf[ID_COL] == bird_id]

    if bird_points.shape[0] < 5:
        print(f"Skipping bird {bird_id} (too few points)")
        continue

    # MCP
    mcp = MultiPoint(bird_points.geometry.tolist()).convex_hull
    mcp_area_km2 = mcp.area / 1e6

    # KDE
    x = bird_points.geometry.x
    y = bird_points.geometry.y
    kde = gaussian_kde(np.vstack([x, y]))

    # Grid
    xmin, xmax = x.min() - 500, x.max() + 500
    ymin, ymax = y.min() - 500, y.max() + 500
    xx, yy = np.mgrid[xmin:xmax:300j, ymin:ymax:300j]
    positions = np.vstack([xx.ravel(), yy.ravel()])
    kde_values = np.reshape(kde(positions).T, xx.shape)

    # 95% threshold
    flat_kde = kde_values.flatten()
    kde_threshold = np.percentile(flat_kde, 5)
    mask = kde_values >= kde_threshold

    # Extract contours
    contours = measure.find_contours(mask.astype(float), 0.5)
    kde_polygons = []

    for contour in contours:
        if len(contour) < 4:
            continue  # Need enough points for valid polygon

        contour_coords = np.column_stack((
            xmin + (xmax - xmin) * contour[:, 1] / 300,
            ymin + (ymax - ymin) * contour[:, 0] / 300
        ))

        try:
            poly = Polygon(contour_coords)
            if poly.is_valid and poly.area > 0:
                kde_polygons.append(poly)
        except Exception as e:
            print(f"Invalid KDE polygon for {bird_id}: {e}")
            continue

    kde_union = gpd.GeoSeries(kde_polygons).union_all()
    kde_area_km2 = kde_union.area / 1e6 if not kde_union.is_empty else 0

    # Plot
    fig, axes = plt.subplots(1, 2, figsize=(12, 6))
    fig.suptitle(f"Bird {bird_id}\nMCP Area: {mcp_area_km2:.2f} km² | KDE 95% Area: {kde_area_km2:.2f} km²")

    # MCP Plot
    bird_points.plot(ax=axes[0], color="blue", markersize=5)
    gpd.GeoSeries([mcp]).plot(ax=axes[0], edgecolor="red", facecolor="none", linewidth=2)
    axes[0].set_title("Minimum Convex Polygon (MCP)")

    # KDE Plot
    axes[1].imshow(np.rot90(kde_values), cmap="viridis", extent=[xmin, xmax, ymin, ymax])
    bird_points.plot(ax=axes[1], color="red", markersize=2)

    if not kde_union.is_empty:
        gpd.GeoSeries([kde_union]).plot(ax=axes[1], edgecolor="black", facecolor="none", linewidth=1)
    else:
        axes[1].text(0.5, 0.5, "No KDE contour", transform=axes[1].transAxes,
                     ha="center", va="center", fontsize=12, color="gray")

    axes[1].set_title("Kernel Density Estimation (95%)")
    plt.tight_layout()
    plt.show()

    print(f"Bird {bird_id}: MCP = {mcp_area_km2:.2f} km² | KDE 95% = {kde_area_km2:.2f} km²")

